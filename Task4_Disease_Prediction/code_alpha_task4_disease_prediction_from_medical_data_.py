import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.datasets import load_breast_cancer

from sklearn.model_selection import train_test_split

from sklearn.preprocessing import StandardScaler

from sklearn.linear_model import LogisticRegression

from sklearn.ensemble import RandomForestClassifier

from sklearn.metrics import accuracy_score
from sklearn.metrics import classification_report
from sklearn.metrics import confusion_matrix

"""## Loading the Dataset

The Breast Cancer Wisconsin dataset is loaded directly from Scikit-Learn.

The dataset contains diagnostic measurements of breast cancer tumors and is commonly used for classification tasks in machine learning.
"""

data = load_breast_cancer()

X = pd.DataFrame(
    data.data,
    columns=data.feature_names
)

y = pd.Series(data.target)

print("Features Shape:", X.shape)
print("Target Shape:", y.shape)

"""## Understanding the Dataset

The dataset consists of multiple medical features extracted from breast tumor images.

The target variable contains:

- 0 = Malignant (Cancerous)
- 1 = Benign (Non-Cancerous)

Understanding the dataset helps identify the structure and quality of the available data.
"""

X.head()

X.info()

X.describe()

"""## Checking Missing Values

Before building machine learning models, it is important to identify missing values and ensure data quality.
"""

X.isnull().sum()

"""## Target Variable Distribution

The following visualization shows the distribution of benign and malignant cases in the dataset.
"""

plt.figure(figsize=(6,4))

sns.countplot(x=y)

plt.title("Breast Cancer Target Distribution")

plt.show()

"""### Correlation Heatmap

A correlation heatmap helps identify relationships among different features.
"""

plt.figure(figsize=(12,10))

sns.heatmap(
    X.corr(),
    cmap="coolwarm"
)

plt.title("Feature Correlation Heatmap")

plt.show()

"""### Feature Distribution

The histogram shows the distribution of one of the important medical features.
"""

plt.figure(figsize=(6,4))

sns.histplot(
    X["mean radius"],
    kde=True
)

plt.title("Distribution of Mean Radius")

plt.show()

"""## Feature Scaling

Feature scaling is applied to standardize numerical values and improve model performance.
"""

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

"""## Splitting the Dataset

The dataset is divided into training and testing sets.

Training data is used for model learning, while testing data is used for performance evaluation.
"""

X_train, X_test, y_train, y_test = train_test_split(
    X_scaled,
    y,
    test_size=0.2,
    random_state=42
)

print("Training Samples:", X_train.shape)
print("Testing Samples:", X_test.shape)

"""## Model 1: Logistic Regression

Logistic Regression is a supervised machine learning algorithm widely used for binary classification problems.
"""

lr = LogisticRegression(
    max_iter=5000
)

lr.fit(
    X_train,
    y_train
)

y_pred_lr = lr.predict(X_test)

lr_accuracy = accuracy_score(
    y_test,
    y_pred_lr
)

print("Logistic Regression Accuracy:", lr_accuracy)

"""## Model 2: Random Forest Classifier

Random Forest combines multiple decision trees to improve prediction accuracy and reduce overfitting.
"""

rf = RandomForestClassifier(
    n_estimators=100,
    random_state=42
)

rf.fit(
    X_train,
    y_train
)

y_pred_rf = rf.predict(X_test)

rf_accuracy = accuracy_score(
    y_test,
    y_pred_rf
)

print("Random Forest Accuracy:", rf_accuracy)

"""## Model Comparison

The performance of both machine learning models is compared using accuracy scores.
"""

print("Logistic Regression Accuracy:", lr_accuracy)

print("Random Forest Accuracy:", rf_accuracy)

"""## Classification Report

The classification report provides precision, recall, F1-score, and support for each class.
"""

print(
    classification_report(
        y_test,
        y_pred_rf
    )
)

"""## Confusion Matrix

A confusion matrix shows the number of correct and incorrect predictions made by the model.
"""

cm = confusion_matrix(
    y_test,
    y_pred_rf
)

plt.figure(figsize=(6,4))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues"
)

plt.xlabel("Predicted")
plt.ylabel("Actual")

plt.title("Confusion Matrix")

plt.show()

